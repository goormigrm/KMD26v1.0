  // 미드필더 — 패스·시야·천재성·퍼스트 터치. 공간을 메우려면 활동량·팀워크·타고난 체력이 필수다.
  MF:["pas","vis","fla","fir","wor","tea","nat"],
  // 수비수 — 수비시 위치 선정·태클·대인마크, 그리고 공중볼과 몸싸움.
  DF:["pos","tck","mar","jum","str"],
  // 골키퍼 — 공중볼 처리·반사신경·1대1·수비 조율·핸들링·킥.
  GK:["aer","ref","one","com","han","kic"]
