function syncLegacyAttrs(a){
  if(!a) return a;
  for(const k in LEGACY_FROM){
    const src=LEGACY_FROM[k];
    let s=0,n=0;
    for(const q of src){ if(typeof a[q]==="number"){ s+=a[q]; n++; } }
    if(n) a[k]=Math.round(s/n);
  }
  return a;
}

